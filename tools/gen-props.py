#!/usr/bin/env python3
"""Turn a stock build.prop into a BoardConfig prop file.

The build installs its own build.prop into the vendor and odm partitions, so
the stock file is dropped from the blob list and its contents are copied here
instead, minus every key the platform owns. Handing a stock build.prop to the
build verbatim drags the OEM fingerprints and release dates along.

Usage:
    ./tools/gen-props.py <stock-tree>
"""

import argparse
import os
import sys

# Prefixes the platform sets for itself. A stock value here either gets
# ignored or fights the build, so none of them are copied.
BLOCKED_PREFIXES = (
    'ro.product.',
    'ro.build.',
    'ro.vendor.build.',
    'ro.odm.build.',
    'ro.system.build.',
    'ro.boot.',
    'ro.bootimage.',
    'ro.crypto.',
    'ro.apex.',
    'ro.runtime.firstboot',
    'ro.vendor.build_date',
    'ro.vendor.product.partition',
)

BLOCKED_EXACT = (
    'ro.build.description',
    'ro.build.fingerprint',
    'ro.product.board',
    'ro.product.hardware',
)

HEADER = """#
# SPDX-FileCopyrightText: The Redmi A5 (serenity) Project
# SPDX-License-Identifier: Apache-2.0
#
"""


def parse(text):
    """Read a build.prop into an ordered list of (key, value)."""
    out = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        if '=' not in line:
            continue
        key, _, value = line.partition('=')
        out.append((key.strip(), value.strip()))
    return out


def blocked(key):
    return key in BLOCKED_EXACT or key.startswith(BLOCKED_PREFIXES)


def emit(pairs, source, out_path):
    kept = [(k, v) for k, v in pairs if not blocked(k)]
    with open(out_path, 'w') as out:
        out.write(HEADER)
        out.write(f'# Generated by tools/gen-props.py from {source}\n')
        out.write(f'# {len(pairs)} keys in, {len(kept)} kept\n\n')
        for key, value in kept:
            out.write(f'{key}={value}\n')
    dropped = len(pairs) - len(kept)
    print(f'{out_path}: {len(kept)} props ({dropped} platform owned keys dropped)')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('stock_tree')
    args = ap.parse_args()

    root = os.path.abspath(args.stock_tree)
    jobs = (
        ('vendor/build.prop', 'vendor.prop'),
        ('odm/etc/build.prop', 'odm.prop'),
    )
    for src, dst in jobs:
        path = os.path.join(root, src)
        if not os.path.isfile(path):
            sys.exit(f'{path} is missing, is {root} the stock tree?')
        with open(path, encoding='utf-8', errors='replace') as handle:
            emit(parse(handle.read()), src, dst)


if __name__ == '__main__':
    main()