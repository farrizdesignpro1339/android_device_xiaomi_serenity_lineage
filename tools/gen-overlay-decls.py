#!/usr/bin/env python3
"""Pick the runtime overlays that apply to a LineageOS build and declare them.

The stock ROM ships 29 overlay apks under vendor/overlay and odm/overlay, all
static, and declares none of them: there is no <overlay> element anywhere in
vendor, odm or product. On stock they are inert, so the declarations have to be
written here.

Most come in pairs or triples, one per platform flavour. The target package in
each manifest decides which one a LineageOS build can take, because a runtime
overlay whose target is missing is dropped at boot with a log line, and one
whose target is not overlayable on that policy is dropped as well. Hence the
skip list and the preference order below rather than shipping all 29.

Usage:
    ./tools/gen-overlay-decls.py <stock-tree> [--list]

Writes vendor/etc/permissions/overlay-decls.xml next to the tree, which
device.mk copies into the vendor partition.
"""

import argparse
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

# Targets a LineageOS build does not have. Dropping the overlay is correct,
# shipping it only produces a boot time RRO failure.
SKIP_TARGETS = {
    # the Marlin3 Wifi overlay pair, the module is not in the build
    'com.android.wifi.uniresources',
    'com.google.android.wifi.resources',
    # the com.unisoc app pair, it comes from cust, not from any partition here
    'com.unisoc',
    # the Go network stack, LineageOS is a full build
    'com.google.android.go.networkstack',
    'com.google.android.connectivity.resources',
}

# Where two apks target the same package, only one can ship: the later name
# wins. The pairs are named after the platform each one was cut for, and the
# keys are basenames because the declaration is per target package, so both
# apks of a pair would be enabled together.
PREFER = [
    # this chip is qogirl6, the vendor says so in ro.vendor.tui.chip
    ('AospBtOverlay_Qogirl6.apk', 'AospBtOverlay.apk'),
    # LineageOS is a full build, not the Go one
    ('unisoc_overlay_core.apk', 'unisoc_overlay_core_go.apk'),
    ('NetworkStackOverlayGsi.apk', 'NetworkStackOverlayGo.apk'),
    ('TetheringConfigOverlayGsi.apk', 'TetheringConfigOverlayGo.apk'),
    # the other way round here: the Go cut targets the AOSP package
    ('UnisocConnectivityOverlayGo.apk', 'UnisocConnectivityOverlayGsi.apk'),
    ('unisoc_overlay_power_qogirl6.apk', 'unisoc_overlay_power_cpuT606.apk'),
    ('unisoc_overlay_power_qogirl6.apk', 'unisoc_overlay_power_cpuT615.apk'),
    ('unisoc_overlay_power_qogirl6.apk', 'unisoc_overlay_power_cpuT616.apk'),
]

HEADER = """<!--
    SPDX-FileCopyrightText: The Redmi A5 (serenity) Project
    SPDX-License-Identifier: Apache-2.0

    Generated by tools/gen-overlay-decls.py.
    The stock ROM declares none of its overlays, this does.
-->"""


def manifest(apk):
    """(package, targetPackage, isStatic) from one apk.

    aapt dump xmltree prints an indented tree, not xml, so it is read as text:
    an attribute line is "A: <name>(0x...)=<value>" or "A: <name>=\"<value>\"",
    and a boolean shows up as its type masked value.
    """
    out = subprocess.run(['aapt', 'dump', 'xmltree', apk, 'AndroidManifest.xml'],
                         capture_output=True, text=True, check=True).stdout

    package = re.search(r'^\s*A: package="([^"]+)"', out, re.M)
    target = re.search(r'^\s*A: android:targetPackage\(0x[0-9a-f]+\)='
                       r'"([^"]+)"', out, re.M)
    static = re.search(r'^\s*A: android:isStatic\(0x[0-9a-f]+\)='
                       r'\(type 0x12\)(0x[0-9a-f]+)', out, re.M)
    is_static = bool(static) and int(static.group(1), 16) != 0
    return (package.group(1) if package else None,
            target.group(1) if target else None,
            is_static)


def collect(stock):
    """Every overlay apk under vendor/overlay and odm/overlay."""
    found = []
    for top in ('vendor', 'odm'):
        base = os.path.join(stock, top, 'overlay')
        if not os.path.isdir(base):
            continue
        for dirpath, _dirs, files in os.walk(base):
            for name in sorted(files):
                if name.endswith('.apk'):
                    full = os.path.join(dirpath, name)
                    found.append((os.path.relpath(full, stock), full))
    return found


def select(overlays):
    """Apply the skip list and the preference order.

    Returns (targets, excluded, dropped). A declaration enables every overlay
    in the partition that targets that package, so losing apk goes into the
    blob exclusion list rather than only being left undeclared.
    """
    by_name = {os.path.basename(rel): rel for rel, _ in overlays}
    losers = {}
    for winner, loser in PREFER:
        if winner in by_name and loser in by_name:
            losers[by_name[loser]] = by_name[winner]

    targets = {}
    excluded, dropped = [], []
    for rel, full in overlays:
        package, target, static = manifest(full)
        name = os.path.basename(rel)
        if target in SKIP_TARGETS:
            dropped.append((rel, target, 'target not in the build'))
            excluded.append(rel)
        elif rel in losers:
            winner = os.path.basename(losers[rel])
            dropped.append((rel, target, f'superseded by {winner}'))
            excluded.append(rel)
        elif not target:
            dropped.append((rel, target, 'no targetPackage in the manifest'))
            excluded.append(rel)
        else:
            targets.setdefault(target, {'static': True, 'apks': []})
            targets[target]['static'] &= static
            targets[target]['apks'].append(rel)

    return targets, sorted(excluded), dropped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('stock_tree')
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument('-o', '--output',
                    default=os.path.join(base, 'configs/overlay/overlay-decls.xml'))
    ap.add_argument('-x', '--exclude',
                    default=os.path.join(base,
                                         'configs/overlay/overlay-exclude.txt'))
    ap.add_argument('--list', action='store_true',
                    help='print the decision and write nothing')
    args = ap.parse_args()

    stock = os.path.abspath(args.stock_tree)
    targets, excluded, dropped = select(collect(stock))

    for target, info in sorted(targets.items()):
        print(f'  keep  {target} ({"static" if info["static"] else "runtime"})')
        for rel in info['apks']:
            print(f'          {rel}')
    for rel, target, why in dropped:
        print(f'  drop  {rel}\n          {target}: {why}')

    if args.list:
        print(f'\n{len(targets)} targets, {len(excluded)} apks excluded')
        return 0

    root = ET.Element('permissions')
    for target, info in sorted(targets.items()):
        node = ET.SubElement(root, 'overlay')
        node.set('targetPackage', target)
        if info['static']:
            node.set('isStatic', 'true')
    ET.indent(root, space='    ')
    body = HEADER + '\n' + ET.tostring(root, encoding='unicode') + '\n'
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, 'w', encoding='utf-8') as out:
        out.write(body)

    with open(args.exclude, 'w', encoding='utf-8') as out:
        out.write('# Overlay apks tools/gen-blobs.py has to leave out.\n')
        out.write('# The losing half of a pair, or one whose target package is\n')
        out.write('# not in the build. Generated by tools/gen-overlay-decls.py.\n')
        for rel in excluded:
            out.write(rel + '\n')

    print(f'\n{len(targets)} targets declared -> {args.output}')
    print(f'{len(excluded)} apks excluded -> {args.exclude}')
    return 0


if __name__ == '__main__':
    sys.exit(main())