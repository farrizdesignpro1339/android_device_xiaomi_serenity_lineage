#!/usr/bin/env python3
"""Build the vendor repo from the blob list, without extract-utils.

extract-utils needs a LineageOS checkout, which this machine does not have, so
the repo is assembled directly: the blobs are copied out of the stock tree and
the makefile and the symlinks are generated from the same list.

The blobs go in with PRODUCT_COPY_FILES rather than as prebuilt modules. That
keeps the vendor repo small and simple, and it is enough as long as nothing in
the build asks for a vendor library by module name, which device.mk arranges by
declaring the few modules it needs itself.

The SYMLINK= directive in the list is flattened here: the blob is the file the
link chain ends at, and every path named in the directive becomes a symlink to
it.

Usage:
    ./tools/make-vendor-repo.py <stock-tree> <vendor-repo>
"""

import argparse
import os
import shutil
import sys

HEADER = ('#\n'
          '# SPDX-FileCopyrightText: The Redmi A5 (serenity) Project\n'
          '# SPDX-License-Identifier: Apache-2.0\n'
          '#\n'
          '# Generated by tools/make-vendor-repo.py, edit the generator.\n'
          '#\n')

# Symlinks whose target is outside the vendor tree, so they cannot come from a
# blob. They are the same two the stock carries.
MANUAL_SYMLINKS = {
    'vendor/odm': '/odm',
    'vendor/firmware/tsx_data': '/mnt/vendor/productinfo/wcn/tsx_bt_data.txt',
}


def parse(line):
    """One list line -> (blob path, [symlink paths])."""
    if ';' in line:
        path, _, rest = line.partition(';')
        links = []
        for directive in rest.split(';'):
            key, _, value = directive.partition('=')
            if key == 'SYMLINK' and value:
                links.extend(v for v in value.split(',') if v)
        return path, links
    return line, []


def load_list(path):
    out = []
    with open(path, encoding='utf-8') as handle:
        for raw in handle:
            raw = raw.strip()
            if raw and not raw.startswith('#'):
                out.append(raw)
    return out


def module_name(blob):
    """A Soong safe module name for one symlink."""
    stem = os.path.basename(blob)
    for ext in ('.so', '.so.1', '.so.1.1', '.so.1.2'):
        if stem.endswith(ext):
            stem = stem[:-len(ext)]
            break
    else:
        stem = os.path.splitext(stem)[0]
    name = blob.replace('/', '_')
    for ch in '-.':
        name = name.replace(ch, '_')
    return f'symlink_{name}_{stem}' if stem else f'symlink_{name}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('stock_tree')
    ap.add_argument('vendor_repo')
    ap.add_argument('-l', '--list', default='proprietary-files.txt')
    ap.add_argument('--prune', action='store_true',
                    help='delete blobs under proprietary/ that the list no '
                         'longer names')
    args = ap.parse_args()

    stock = os.path.abspath(args.stock_tree)
    repo = os.path.abspath(args.vendor_repo)
    blobs = os.path.join(repo, 'proprietary')
    os.makedirs(blobs, exist_ok=True)

    entries = load_list(args.list)
    if not entries:
        sys.exit(f'{args.list} is empty, run tools/gen-blobs.py first')

    symlinks = {}
    copied = 0
    total = 0
    missing = []
    for entry in entries:
        blob, links = parse(entry)
        src = os.path.join(stock, blob)
        dst = os.path.join(blobs, blob)
        if not os.path.isfile(src):
            missing.append(blob)
            continue
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if not os.path.exists(dst) or os.path.getsize(dst) != os.path.getsize(src):
            shutil.copy2(src, dst)
        copied += 1
        total += os.path.getsize(src)
        for link in links:
            # Absolute target, the way extract-utils writes it. A relative one
            # breaks as soon as the link and the file are not in the same
            # directory, which hw/vulkan.ums9230.so and the egl copy are not.
            symlinks[link] = '/' + blob

    if args.prune:
        wanted = {os.path.join(blobs, e.partition(';')[0]) for e in entries}
        stale = 0
        for dirpath, _dirs, files in os.walk(blobs, topdown=False):
            for name in files:
                full = os.path.join(dirpath, name)
                if full not in wanted:
                    os.remove(full)
                    stale += 1
            if not os.listdir(dirpath):
                os.rmdir(dirpath)
        print(f'{stale} stale blobs removed')

    # Prebuilt apks, the overlay ones. They may not be copied, they have to be
    # modules, and they land in the overlay directory of their partition. They
    # are not in the blob list, so they are copied here as the source of the
    # module.
    apks = []
    for part in ('vendor', 'odm'):
        base = os.path.join(stock, part, 'overlay')
        if not os.path.isdir(base):
            continue
        for dirpath, _dirs, files in os.walk(base):
            for name in sorted(files):
                if not name.endswith('.apk'):
                    continue
                src = os.path.join(dirpath, name)
                rel = os.path.relpath(src, stock)
                dst = os.path.join(blobs, rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                if not os.path.exists(dst) or \
                        os.path.getsize(dst) != os.path.getsize(src):
                    shutil.copy2(src, dst)
                apks.append(rel)

    # The VINTF metadata may not be copied, the build refuses it. The
    # fragments go out as vintf_fragments modules instead, the manifest and the
    # compatibility matrix are declared in the device tree.
    def is_vintf(blob):
        return '/etc/vintf/' in blob

    fragments = []
    copies = []
    for entry in sorted(entries):
        blob = entry.partition(';')[0]
        if is_vintf(blob):
            fragments.append(blob)
        else:
            copies.append(blob)

    mk = [HEADER, '\nPRODUCT_COPY_FILES += \\\n']
    for blob in copies:
        mk.append(f'    proprietary/{blob}:{blob} \\\n')
    mk.append('\n')
    if fragments:
        mk.append('\n# the VINTF fragments, they are modules and not copies\n')
        mk.append('PRODUCT_PACKAGES += \\\n')
        for rel in fragments:
            name = os.path.basename(rel)[:-len('.xml')]
            mk.append(f'    {name} \\\n')
    if apks:
        mk.append('\n# the prebuilt overlays, they are modules and not copies\n')
        mk.append('PRODUCT_PACKAGES += \\\n')
        for rel in apks:
            name = os.path.basename(rel)[:-len('.apk')]
            mk.append(f'    {name} \\\n')
    with open(os.path.join(repo, 'serenity-vendor.mk'), 'w') as out:
        out.writelines(mk)

    # The symlinks, both the flattened chains and the two manual ones
    # No soong_namespace here on purpose. A namespace of its own would have to
    # be listed in PRODUCT_SOONG_NAMESPACES, and the device tree only lists
    # itself, so the modules below would never be built. Leaving them in the
    # global namespace is what extract-utils does as well.
    bp = ['//', '// SPDX-FileCopyrightText: The Redmi A5 (serenity) Project',
          '// SPDX-License-Identifier: Apache-2.0', '//', '']
    for rel in fragments:
        name = os.path.basename(rel)[:-len('.xml')]
        bp.append('// a VINTF fragment, it may not be copied')
        bp.append('vintf_fragments {')
        bp.append(f'    name: "{name}",')
        bp.append(f'    src: "proprietary/{rel}",')
        bp.append('    relative_install_path: "etc/vintf/manifest",')
        bp.append('    vendor: true,')
        bp.append('}')
        bp.append('')
    for rel in apks:
        part = rel.split('/')[0]
        name = os.path.basename(rel)[:-len('.apk')]
        bp.append('// a runtime overlay, a prebuilt apk may not be copied')
        bp.append('prebuilt_etc {')
        bp.append(f'    name: "{name}",')
        bp.append(f'    src: "proprietary/{rel}",')
        bp.append('    sub_dir: "overlay",')
        bp.append(f'    filename: "{os.path.basename(rel)}",')
        # an apk is not an elf, there is nothing to strip, and the flag to
        # say so is not in this version of soong.
        # prebuilt_etc has no odm flag either, the overlays that the stock kept
        # in odm go to the vendor overlay directory instead, which the
        # runtime overlay manager scans just the same.
        bp.append('    vendor: true,')
        bp.append('}')
        bp.append('')
    for link, target in sorted(symlinks.items()):
        bp.append('install_symlink {')
        bp.append(f'    name: "{module_name(link)}",')
        bp.append('    soc_specific: true,')
        bp.append(f'    installed_location: "{os.path.dirname(link)}",')
        bp.append(f'    symlink_target: "{target}",')
        bp.append('}')
        bp.append('')
    for link, target in sorted(MANUAL_SYMLINKS.items()):
        if link.startswith('vendor/firmware/'):
            continue
        bp.append('install_symlink {')
        bp.append(f'    name: "{module_name(link)}",')
        bp.append('    soc_specific: true,')
        bp.append(f'    installed_location: "{os.path.dirname(link)}",')
        bp.append(f'    symlink_target: "{target}",')
        bp.append('}')
        bp.append('')
    with open(os.path.join(repo, 'Android.bp'), 'w') as out:
        out.write('\n'.join(bp))

    manual = [l for l in MANUAL_SYMLINKS if not l.startswith('vendor/firmware/')]
    print(f'{len(symlinks)} symlinks from the list, {len(manual)} declared by hand')

    with open(os.path.join(repo, 'README.md'), 'w') as out:
        out.write(
            '# Vendor blobs for the Redmi A5 (serenity)\n\n'
            'Generated from the blob list by `tools/make-vendor-repo.py`,\n'
            'do not edit by hand.\n\n'
            f'Source stock tree: the Redmi A5 factory ROM\n'
            f'Blobs: {copied}, {total / 1048576:.0f} MiB\n'
            f'Symlinks: {len(symlinks) + len(MANUAL_SYMLINKS) - 1}, one of them a '
            f'path outside the tree\n')

    print(f'{copied} blobs copied, {total / 1048576:.0f} MiB')
    if missing:
        print(f'{len(missing)} listed blobs not in the stock tree:',
              file=sys.stderr)
        for blob in missing[:10]:
            print(f'  {blob}', file=sys.stderr)
    return 1 if missing else 0


if __name__ == '__main__':
    sys.exit(main())