#!/usr/bin/env python3
"""Write the vendor sepolicy tree from the stock policy.

genpolicy.py works out what has to be ported and prints it, this writes the
result to sepolicy/vendor. Two halves:

  contexts   the stock vendor_file_contexts, property_contexts, service_contexts,
             vendor_hwservice_contexts and vndservice_contexts, copied over with
             the _NN_NN version suffixes stripped, because every blob needs its
             label and the stock file is the only complete answer

  rules      a .te per ported domain, built from the stock allow, dontaudit and
             typetransition rules whose source is that domain, plus a
             declaration for every type, attribute and domain the rules and the
             contexts mention and the platform does not already provide

Usage: ./tools/emit.py [--dry-run]
"""

import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import genpolicy as gp  # noqa: E402
from cil import inner, strip_version  # noqa: E402

HEADER = ('#\n'
          '# SPDX-FileCopyrightText: The Redmi A5 (serenity) Project\n'
          '# SPDX-License-Identifier: Apache-2.0\n'
          '#\n'
          '# Generated by tools/emit.py from the stock policy.\n'
          '# Review before shipping, the platform side is assumed.\n'
          '#\n')

# The version suffix the build re-adds from PLATFORM_SECURITY_PATCH.
VERSION = re.compile(r'\b([A-Za-z0-9_]+?)_\d+_\d+\b')

DECL = {
    'file': 'type {name}, file_type, vendor_file_type;',
    'device': 'type {name}, dev_type;',
    'property': 'type {name}, property_type, vendor_property_type;',
    'service': 'type {name}, service_manager_type;',
    'hwservice': 'type {name}, hwservice_manager_type;',
    'sysfs': 'type {name}, sysfs_type, fs_type;',
    'plain': 'type {name};',
}

# No name filter is needed here. genpolicy's build_platform() reads the stock
# plat_pub_versioned.cil, which lists every type and attribute the platform
# hands the vendor, core attributes included, and those are already excluded
# from the declaration set because they are in `known`. A name that is not in
# that file is a vendor type and this tree has to declare it, even when it
# looks like a platform hal_ name: hal_sensors_hwservice is in the file and
# hal_tui_hwservice is not.


def restrip(text):
    return VERSION.sub(r'\1', text)


def perms_of(expr):
    """The permission list out of a "(class (p1 p2))" expression."""
    parts = inner(expr)
    cls = restrip(parts[0]) if parts else ''
    perms = ' '.join(inner(parts[1])) if len(parts) > 1 else ''
    return cls, restrip(perms)


def fmt_genfscon(args):
    """(genfscon FS "path" (u object_r type ((s0) (s0)))) -> the .te form.

    The CIL context carries the class, the type and the context as separate
    s-expressions; the .te line wants them merged into u:object_r:type:s0.
    """
    fs = restrip(args[0])
    path = args[1]
    parts = inner(args[2])
    if len(parts) < 3:
        return None
    # u, the role, the type, then the context; a CIL context is a class
    # context pair and the same one twice, so the first is the one to take
    cls = restrip(parts[0])
    role = restrip(parts[1])
    typ = restrip(parts[2])
    context = 's0'
    if len(parts) > 3:
        try:
            context = inner(inner(parts[3])[0]).strip('()') or 's0'
        except Exception:
            context = 's0'
    return f'genfscon {fs} {path} {cls}:{role}:{typ}:{context}'


def fmt_rule(head, args):
    """One CIL rule as the classic .te form checkpolicy reads.

    The stock policy is CIL, so its rules are s-expressions like
    (allow src tgt (file (read write))). That is not valid .te: the class goes
    after a colon and the permissions follow it directly, braced only when
    there is more than one.
    """
    if head == 'allowx':
        # (allowx SRC TGT (ioctl <driver class> (<ioctl list>))) is an extended
        # ioctl permission, which .te spells allowxperm
        src, tgt, expr = args[0], args[1], args[2]
        parts = inner(expr)
        if len(parts) < 3:
            return None
        # an ioctl list is either plain numbers or (range a b), which .te
        # writes as "a - b"
        listed = []
        for item in inner(parts[2]):
            bits = inner(item) if item.startswith('(') else [item]
            if len(bits) == 3 and bits[0] == 'range':
                listed.append(f'{bits[1]} - {bits[2]}')
            else:
                listed.append(restrip(item))
        ioctls = ' '.join(listed)
        return (f'allowxperm {restrip(src)} {restrip(tgt)}:ioctl '
                f'ioctl {{ {ioctls} }};')
    if head in ('allow', 'dontaudit', 'auditallow'):
        src, tgt, expr = args[0], args[1], args[2]
        cls, perms = perms_of(expr)
        perms = perms.strip('{} ')
        if len(perms.split()) > 1:
            perms = '{ ' + perms + ' }'
        return f'{head} {restrip(src)} {restrip(tgt)}:{cls} {perms};'
    if head == 'typetransition':
        # CIL drops the parentheses, so four arguments mean no name
        src, tgt = restrip(args[0]), restrip(args[1])
        rest = [restrip(a) for a in args[2:]]
        return (f'type_transition {src} {tgt}:{rest[0]} '
                f'{" ".join(rest[1:])};')
    return None


def write(path, body):
    with open(path, 'w', encoding='utf-8') as out:
        out.write(HEADER)
        out.write(body)
    print(f'  wrote {os.path.relpath(path, gp.TREE)}')


def emit_contexts(dry):
    """Copy the stock contexts files, dropping the version suffixes."""
    outdir = os.path.join(gp.TREE, 'sepolicy/vendor')
    if not dry:
        os.makedirs(outdir, exist_ok=True)
    for kind, paths in gp.CONTEXTS.items():
        name = gp.CONTEXT_FILES_HEAD[kind]
        lines = []
        for path in paths:
            if not os.path.isfile(path):
                continue
            with open(path, encoding='utf-8', errors='ignore') as handle:
                for raw in handle:
                    stripped = strip_version(raw.rstrip('\r\n'))
                    if stripped.strip():
                        lines.append(stripped)
        if not lines:
            continue
        body = '\n'.join(lines) + '\n'
        if dry:
            print(f'  {name}: {len(lines)} lines')
        else:
            write(os.path.join(outdir, name), body)


def emit_policy(dry):
    """Declare the missing types and copy the rules of every ported domain."""
    public, plat_vendor = gp.build_platform()
    tree_names = gp.build_tree_names()
    kinds, attributes, _rules, genfs = gp.build_stock_kinds()
    labels = gp.domain_labels()

    domains = {}
    for exec_path, (domain, action, label) in labels.items():
        rec = domains.setdefault(domain, {'action': action, 'label': label,
                                          'exec': []})
        rec['exec'].append(exec_path)
        if action == 'declare':
            rec['action'] = 'declare'

    # what the platform already declares, as opposed to known below, which also
    # carries the names this tree is about to declare
    platform = set(public) | set(plat_vendor) | set(tree_names)
    known = set(platform) | set(domains)

    # Rules whose source is a domain this tree ports
    per_domain = defaultdict(list)
    referenced = defaultdict(set)
    for path in gp.STOCK_CIL:
        for head, args, _src in gp.load([path]):
            if head not in ('allow', 'allowx', 'dontaudit', 'auditallow',
                            'typetransition'):
                continue
            if not args:
                continue
            src = strip_version(args[0].strip('()'))
            if src not in domains:
                continue
            for name in gp.idents(args[1]):
                referenced[name].add(src)
            if head == 'typetransition' and len(args) > 3:
                for name in gp.idents(args[3]):
                    referenced[name].add(src)
            line = fmt_rule(head, args)
            if line:
                per_domain[src].append((head, args, line))

    # Everything the contexts label also has to exist
    wanted = set()
    for name, _srcs in referenced.items():
        n = strip_version(name)
        if n not in known and not n.isdigit():
            wanted.add(n)
    for kind, paths in gp.CONTEXTS.items():
        for path in paths:
            if not os.path.isfile(path):
                continue
            with open(path, encoding='utf-8', errors='ignore') as handle:
                for raw in handle:
                    for match in re.finditer(
                            r'u:object_r:([A-Za-z0-9_-]+)', strip_version(raw)):
                        n = strip_version(match.group(1))
                        if n not in known and not n.isdigit():
                            wanted.add(n)

    # A declared domain brings its own <domain>_exec with it, so those names
    # must not also land in the bulk declaration files
    reserved = {f'{name}_exec' for name, rec in domains.items()
                if rec['action'] == 'declare'}
    wanted -= reserved

    def kind_of(name):
        marks = kinds.get(name, set())
        if 'attribute' in marks:
            return 'attribute'
        if 'attr:file_type' in marks:
            return 'file'
        if 'attr:dev_type' in marks:
            return 'device'
        if 'attr:property_type' in marks:
            return 'property'
        if 'attr:service_manager_type' in marks:
            return 'service'
        if 'attr:hwservice_manager_type' in marks:
            return 'hwservice'
        if 'attr:sysfs_type' in marks:
            return 'sysfs'
        return 'plain'

    outdir = os.path.join(gp.TREE, 'sepolicy/vendor')
    if not dry:
        os.makedirs(outdir, exist_ok=True)

    # Declarations, one file per kind so a stock attribute set stays readable
    buckets = defaultdict(list)
    for name in sorted(wanted):
        buckets[kind_of(name)].append(name)
    for kind, names in sorted(buckets.items()):
        if kind == 'attribute':
            body = '\n'.join(f'attribute {n};' for n in names) + '\n'
        else:
            body = '\n'.join(DECL[kind].format(name=n) for n in names) + '\n'
        if dry:
            print(f'  {kind}: {len(names)} declarations')
        else:
            write(os.path.join(outdir, f'{kind}s.te'), body)

    # One file per domain
    for domain, rec in sorted(domains.items()):
        body = []
        if rec['action'] == 'declare':
            # The platform may already declare the domain, tee for one, in
            # which case only its rules belong here
            if domain not in platform:
                body.append(f'type {domain}, domain;')
                body.append(f'init_daemon_domain({domain})')
            if f'{domain}_exec' not in platform:
                body.append(f'type {domain}_exec, exec_type, file_type, '
                            f'vendor_file_type;')
        for head, args, line in per_domain.get(domain, []):
            body.append(line)
        if not body:
            continue
        if dry:
            print(f'  {domain}: {len(body)} lines')
        else:
            write(os.path.join(outdir, f'{domain}.te'), '\n'.join(body) + '\n')

    # genfscon lines for the sysfs and proc types this tree declares
    genfs_lines = []
    for args, _src in genfs:
        if len(args) < 3:
            continue
        if not any(strip_version(n) in wanted for n in gp.idents(args[2])):
            continue
        line = fmt_genfscon(args)
        if line:
            genfs_lines.append(line)
    if genfs_lines:
        body = '\n'.join(sorted(set(genfs_lines))) + '\n'
        if dry:
            print(f'  genfs_contexts: {len(genfs_lines)} lines')
        else:
            write(os.path.join(outdir, 'genfs_contexts'), body)

    print(f'  domains ported: {len(domains)}, declarations: {len(wanted)}, '
          f'rules: {sum(len(v) for v in per_domain.values())}')


def main():
    dry = '--dry-run' in sys.argv
    print('contexts')
    emit_contexts(dry)
    print('policy')
    emit_policy(dry)
    return 0


if __name__ == '__main__':
    sys.exit(main())